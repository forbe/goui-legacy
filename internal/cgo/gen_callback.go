//go:build ignore

// gen_callback.go generates the callback entry tables (zcallback_amd64.s and
// zcallback_arm64.s). Each table entry is a fixed-size instruction sequence
// that records its own index and jumps to the common thunk
// goui_internal_cgo_callbackasm1 implemented in callback_*.s.
//
// Run it with: go run gen_callback.go
package main

import (
	"bytes"
	"fmt"
	"os"
)

// maxCallback must be kept in sync with cbMaxCallbacks in callback.go.
const maxCallback = 1024

func main() {
	genAmd64()
	genArm64()
}

func genAmd64() {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by gen_callback.go. DO NOT EDIT.

//go:build linux || darwin || windows

// External C code calls into goui_internal_cgo_callbackasm at an offset
// corresponding to the callback index. goui_internal_cgo_callbackasm is a table of
// CALL instructions (5 bytes each). The common thunk goui_internal_cgo_callbackasm1
// recovers the callback index from the return address pushed by the CALL.

#include "textflag.h"

// func cbasmBaseAddr() uintptr
TEXT ·cbasmBaseAddr(SB), NOSPLIT, $0-8
	MOVQ $goui_internal_cgo_callbackasm(SB), AX
	MOVQ AX, ret+0(FP)
	RET

TEXT goui_internal_cgo_callbackasm(SB), NOSPLIT|NOFRAME, $0
`)
	for i := 0; i < maxCallback; i++ {
		buf.WriteString("\tCALL goui_internal_cgo_callbackasm1(SB)\n")
	}
	write("zcallback_amd64.s", buf.Bytes())
}

func genArm64() {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by gen_callback.go. DO NOT EDIT.

//go:build linux || darwin

// External C code calls into goui_internal_cgo_callbackasm at an offset
// corresponding to the callback index. goui_internal_cgo_callbackasm is a table of
// MOVD+B instructions (8 bytes each). The MOVD loads the callback index into
// R12 and the B branches to the common thunk goui_internal_cgo_callbackasm1.

#include "textflag.h"

// func cbasmBaseAddr() uintptr
TEXT ·cbasmBaseAddr(SB), NOSPLIT, $0-8
	MOVD $goui_internal_cgo_callbackasm(SB), R0
	MOVD R0, ret+0(FP)
	RET

TEXT goui_internal_cgo_callbackasm(SB), NOSPLIT|NOFRAME, $0
`)
	for i := 0; i < maxCallback; i++ {
		fmt.Fprintf(&buf, "\tMOVD $%d, R12\n\tB    goui_internal_cgo_callbackasm1(SB)\n", i)
	}
	write("zcallback_arm64.s", buf.Bytes())
}

func write(name string, data []byte) {
	if err := os.WriteFile(name, data, 0o644); err != nil {
		panic(err)
	}
	fmt.Println("generated", name)
}
